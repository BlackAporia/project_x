// Bundle scripts/site-crypto.ts into site/vendor/crypto.js (committed: the website has no build step).
import { build } from 'esbuild';

await build({
  entryPoints: ['scripts/site-crypto.ts'],
  outfile: 'site/vendor/crypto.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'eof',
  banner: { js: '// Generated by scripts/build-site-crypto.mjs from scripts/site-crypto.ts - do not edit.' },
});
console.log('wrote site/vendor/crypto.js');
